// Command apikotlin generates the Android client's wire types from the Go wire
// types in internal/http/dto.
//
// The same idea, and the same source, as the TypeScript: renaming a json tag in
// Go should be a compile error in every client, not a bug somebody finds on a
// phone. The web client gets that through api/openapi.yaml and
// openapi-typescript; Android gets it here.
//
// Generated from the GO rather than from the spec, deliberately. The spec is
// itself generated from those structs, so going through it would add a
// translation step without adding a source of truth - and the Go carries
// optionality exactly (a pointer or omitempty), which is the property a
// non-nullable Kotlin type depends on being right.
//
//	make api-kotlin    # regenerate
//	make generate      # the whole contract, every language
//
// `-check` fails when the file on disk is stale, which is what `make lint`
// runs so that a changed struct cannot be committed with the clients still
// describing the old one.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"scm.poniatowski.dev/adam/lexarii/scripts/wiretypes"
)

func main() {
	var (
		dtoDir = flag.String("dto", "internal/http/dto", "package holding the wire types")
		out    = flag.String("out", "android/app/src/main/kotlin/com/lexarii/app/api/Types.gen.kt", "file to write")
		pkg    = flag.String("package", "com.lexarii.app.api", "Kotlin package")
		check  = flag.Bool("check", false, "fail if the file on disk is out of date")
	)
	flag.Parse()

	generated, err := generate(*dtoDir, *pkg)
	if err != nil {
		fmt.Fprintln(os.Stderr, "apikotlin:", err)
		os.Exit(1)
	}

	if *check {
		current, err := os.ReadFile(*out)
		if err != nil {
			fmt.Fprintf(os.Stderr, "apikotlin: %v; run `make api-kotlin`\n", err)
			os.Exit(1)
		}
		if !bytes.Equal(current, generated) {
			fmt.Fprintf(os.Stderr,
				"apikotlin: %s is out of date; run `make api-kotlin`\n", *out)
			os.Exit(1)
		}
		fmt.Printf("%s is up to date\n", *out)
		return
	}

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "apikotlin:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, generated, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "apikotlin:", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s\n", *out)
}

func generate(dtoDir, pkg string) ([]byte, error) {
	types, err := wiretypes.Read(dtoDir)
	if err != nil {
		return nil, err
	}

	names := make([]string, 0, len(types))
	for name := range types {
		names = append(names, name)
	}
	// Sorted, so two runs of the same source produce the same bytes. The
	// Android build has to be reproducible for F-Droid, and a generated file
	// whose order came from map iteration would make it not.
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: AGPL-3.0-or-later\n")
	b.WriteString("//\n")
	b.WriteString("// GENERATED by scripts/apikotlin from internal/http/dto. DO NOT EDIT.\n")
	b.WriteString("// Run `make api-kotlin` after changing a wire type.\n")
	b.WriteString("\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import kotlinx.serialization.SerialName\n")
	b.WriteString("import kotlinx.serialization.Serializable\n")
	b.WriteString("import kotlinx.serialization.json.JsonElement\n")

	for _, name := range names {
		b.WriteString("\n")
		writeType(&b, types[name], types)
	}
	return b.Bytes(), nil
}

// writeType writes one wire type: a data class, an enum, or a typealias.
func writeType(b *bytes.Buffer, t wiretypes.Struct, types map[string]wiretypes.Struct) {
	if len(t.Fields) == 0 {
		writeNamedString(b, t)
		return
	}

	writeDoc(b, t.Doc, "")
	b.WriteString("@Serializable\n")
	fmt.Fprintf(b, "data class %s(\n", t.Name)

	// Embedded structs are spliced in where they stand, because that is what
	// Go does when it marshals one.
	fields := wiretypes.Flatten(t.Fields, types, map[string]bool{t.Name: true}, func(name string) {
		fmt.Fprintf(os.Stderr, "apikotlin: a wire type embeds %s, which is not one\n", name)
		os.Exit(1)
	})

	for i, f := range fields {
		writeDoc(b, f.Doc, "    ")
		property := propertyName(f.JSON)
		if property != f.JSON {
			fmt.Fprintf(b, "    @SerialName(%q)\n", f.JSON)
		}
		kind := kotlinType(f.Type)
		if f.Required {
			fmt.Fprintf(b, "    val %s: %s", property, kind)
		} else {
			// Optional on the wire becomes nullable WITH a default, so a
			// response that omits the field decodes rather than throwing, and
			// so a caller constructing one does not have to name it.
			fmt.Fprintf(b, "    val %s: %s? = null", property, kind)
		}
		if i < len(fields)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString(")\n")
}

// writeNamedString handles a named string type: an enum when it has declared
// constants, and a plain alias when it does not.
func writeNamedString(b *bytes.Buffer, t wiretypes.Struct) {
	if len(t.Values) == 0 {
		writeDoc(b, t.Doc, "")
		fmt.Fprintf(b, "typealias %s = String\n", t.Name)
		return
	}

	writeDoc(b, t.Doc, "")
	b.WriteString("@Serializable\n")
	fmt.Fprintf(b, "enum class %s {\n", t.Name)
	for i, v := range t.Values {
		fmt.Fprintf(b, "    @SerialName(%q)\n", v)
		fmt.Fprintf(b, "    %s", enumConstant(v))
		if i < len(t.Values)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n")
}

// kotlinType maps a Go type onto its Kotlin equivalent.
func kotlinType(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.StarExpr:
		// A pointer is the same type; its nullability is carried by the
		// field's Required flag rather than here, so that a pointer inside a
		// list does not produce List<T?>.
		return kotlinType(t.X)

	case *ast.ArrayType:
		return "List<" + kotlinType(t.Elt) + ">"

	case *ast.MapType:
		return "Map<" + kotlinType(t.Key) + ", " + kotlinType(t.Value) + ">"

	case *ast.SelectorExpr:
		switch t.Sel.Name {
		case "Time":
			// RFC3339 text, which is what the wire carries. Left as a String
			// rather than pulling kotlinx-datetime into the generated file:
			// the client can parse where it needs a date, and every dependency
			// in an F-Droid build is one more thing that has to be libre and
			// reproducible.
			return "String"
		case "RawMessage":
			return "JsonElement"
		default:
			return t.Sel.Name
		}

	case *ast.InterfaceType:
		return "JsonElement"

	case *ast.Ident:
		switch t.Name {
		case "string":
			return "String"
		case "bool":
			return "Boolean"
		case "int", "int8", "int16", "int32", "uint8", "uint16", "uint32":
			return "Int"
		case "int64", "uint", "uint64":
			// Sizes and counts of bytes come over as int64 and genuinely
			// exceed 2^31 for a large library.
			return "Long"
		case "float32", "float64":
			return "Double"
		case "any":
			return "JsonElement"
		default:
			// Another wire type in the same package.
			return t.Name
		}

	default:
		// Nothing in dto reaches this today. JsonElement is the honest answer
		// for a shape this does not know, and it decodes rather than failing.
		return "JsonElement"
	}
}

// writeDoc renders a doc comment as KDoc.
//
// A doc comment containing "*/" would close the block early and leave the rest
// of it as code. Broken with a space rather than with a zero-width character:
// an invisible fix in generated source is worse than a visible one.
func writeDoc(b *bytes.Buffer, doc, indent string) {
	if doc == "" {
		return
	}
	fmt.Fprintf(b, "%s/** %s */\n", indent, strings.ReplaceAll(doc, "*/", "* /"))
}

// propertyName turns a JSON name into a Kotlin property name.
//
// The wire is camelCase by convention and Kotlin properties are too, so this
// is usually the identity - but a name that is a Kotlin keyword has to be
// escaped, or the generated file does not compile.
func propertyName(json string) string {
	if kotlinKeywords[json] {
		return "`" + json + "`"
	}
	return json
}

// kotlinKeywords are the hard keywords, which cannot be used as identifiers
// without backticks. Soft and modifier keywords are fine as property names.
var kotlinKeywords = map[string]bool{
	"as": true, "break": true, "class": true, "continue": true, "do": true,
	"else": true, "false": true, "for": true, "fun": true, "if": true,
	"in": true, "interface": true, "is": true, "null": true, "object": true,
	"package": true, "return": true, "super": true, "this": true, "throw": true,
	"true": true, "try": true, "typealias": true, "typeof": true, "val": true,
	"var": true, "when": true, "while": true,
}

// enumConstant turns a wire value into a Kotlin enum constant name.
func enumConstant(value string) string {
	var b strings.Builder
	for _, r := range value {
		switch {
		case r >= 'a' && r <= 'z':
			b.WriteRune(r - 32)
		case r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	name := b.String()
	// A constant cannot begin with a digit.
	if name != "" && name[0] >= '0' && name[0] <= '9' {
		name = "_" + name
	}
	if name == "" {
		name = "UNKNOWN"
	}
	return name
}
